// ContestServiceHandler is an implementation of the meurpg.play.v1.ContestService service.
type ContestServiceHandler interface {
	// GetContestState is every contest fact of the combat the caller may read: the
	// contests they are in (the master: all), the Hide actions, whether they are
	// hidden, the Helps that hold, the grapples, and who is surprised. IDEMPOTENT.
	//
	// Errors: `not_found` (the combat is not in this campaign's session, or the caller
	// is not a member).
	GetContestState(context.Context, *connect.Request[v1.GetContestStateRequest]) (*connect.Response[v1.GetContestStateResponse], error)
	// StartContest begins a grapple or a shove (the initiator rolls Strength (Athletics)
	// against the target's Athletics or Acrobacia, SRD 5.1, "Grappling"), an escape from a
	// grapple (the grappled creature uses its action) or, for the master, a grapple that
	// came from a creature's attack with a fixed escape DC (kind ESCAPE_DC, purpose
	// GRAPPLE: nobody rolls, the target is Grappled at once and the master's escape_dc
	// is kept). A grapple or a shove spends one attack of the Attack action (the action
	// when it is the first), an escape spends the action, in the same transaction that
	// opens the contest. The player starts it for their own combatant on its turn; the
	// master for any combatant (an NPC's turn too). An ESCAPE with a fixed DC resolves at
	// once; any other contest waits for the defender (RespondContest).
	//
	// Errors:
	//   - `not_found`: the combat, the combatant or the target is not found for the
	//     caller (a hidden NPC is not found).
	//   - `permission_denied`: the caller is a player and the initiator is not theirs.
	//   - `invalid_argument`: the purpose, the kind, the skill or the roll is not valid.
	//   - `failed_precondition`: EncounterBlocked (NOT_ACTIVE, NOT_YOUR_TURN, ACTION_USED,
	//     ATTACKS_USED, TARGET_OUT_OF_REACH with `missing_ft`, TARGET_DEFEATED, NOT_PLACED,
	//     COMBATANT_DOWN, WRONG_DICE_MODE) or ContestBlocked (TARGET_TOO_BIG, CONTEST_OPEN,
	//     NOT_GRAPPLED, SURPRISED).
	StartContest(context.Context, *connect.Request[v1.StartContestRequest]) (*connect.Response[v1.StartContestResponse], error)
	// RespondContest is the defender's roll: Strength (Athletics) or Dexterity
	// (Acrobacia), at the defender's choice (SRD 5.1, "Grappling"). The defender's
	// player answers for their own character, or leaves the roll to the master
	// (defer_to_master, with the skill they choose); the master answers for an NPC (he
	// picks the skill, which the app suggests by the higher modifier, and rolls in the
	// app or types the d20), or for a player who has not answered. The totals are
	// compared: the higher wins, a tie changes nothing. A won grapple makes the target
	// Grappled; a lost one changes nothing; a won escape frees the creature. A won shove
	// waits for its winner's choice (ResolveShove).
	//
	// Errors:
	//   - `not_found`, `permission_denied`, `invalid_argument` as StartContest.
	//   - `failed_precondition`: ContestBlocked NOT_AWAITING, or EncounterBlocked
	//     WRONG_DICE_MODE.
	RespondContest(context.Context, *connect.Request[v1.RespondContestRequest]) (*connect.Response[v1.RespondContestResponse], error)
	// ResolveShove is the choice of a won shove: knock the target prone or push it 5
	// feet straight away from the shover (SRD 5.1, "Shoving a Creature"). Called by the
	// one that won, the initiator's player (the master for an NPC and for any shove). The
	// new square is the server's, never the client's. PUSH on a blocked square is
	// `failed_precondition` PUSH_BLOCKED; STAYS says the target does not leave its place
	// and is valid only when the push is blocked. A grappled target that leaves the
	// grappler's reach is released.
	//
	// Errors:
	//   - `failed_precondition` (ContestBlocked): NOT_AWAITING, PUSH_BLOCKED.
	ResolveShove(context.Context, *connect.Request[v1.ResolveShoveRequest]) (*connect.Response[v1.ResolveShoveResponse], error)
	// CloseContest ends a contest that waits for an answer with no result: the master
	// alone ("encerrar a disputa"). The action it spent stays spent.
	//
	// Errors: `failed_precondition` (ContestBlocked): NOT_AWAITING.
	CloseContest(context.Context, *connect.Request[v1.CloseContestRequest]) (*connect.Response[v1.CloseContestResponse], error)
	// ReleaseGrapple lets the grappled creature go: the grappler whenever it likes (no
	// action, SRD 5.1, "Grappling"), or the master. The Grappled condition ends.
	//
	// Errors: `failed_precondition` (ContestBlocked): NOT_GRAPPLED.
	ReleaseGrapple(context.Context, *connect.Request[v1.ReleaseGrappleRequest]) (*connect.Response[v1.ReleaseGrappleResponse], error)
	// Hide is the Hide action: a Dexterity (Stealth) check (SRD 5.1, "Hide"), spent from
	// the action (the Hide of the standard actions) or from the bonus action
	// (a feature that gives Hide as a bonus action, the rogue's Cunning Action). It
	// waits for the master (ResolveHide). The player rolls for their own combatant on
	// its turn; the master for any.
	//
	// Errors: `failed_precondition`: EncounterBlocked (NOT_ACTIVE, NOT_YOUR_TURN,
	// ACTION_USED, BONUS_ACTION_USED, WRONG_DICE_MODE) or ContestBlocked (NOT_AVAILABLE,
	// SURPRISED).
	Hide(context.Context, *connect.Request[v1.HideRequest]) (*connect.Response[v1.HideResponse], error)
	// ResolveHide is the master's decision on a Hide: he applies it (the hider is
	// hidden from the creatures that do not notice it, one state per creature; the
	// master may mark any creature as seeing the hider clearly) or refuses it (no place
	// to hide). Only the master.
	//
	// Errors: `failed_precondition` (ContestBlocked): HIDE_NOT_PENDING.
	ResolveHide(context.Context, *connect.Request[v1.ResolveHideRequest]) (*connect.Response[v1.ResolveHideResponse], error)
	// RevealHider ends a combatant's hiding for every creature (SRD 5.1, "Hiding": the
	// DM decides when circumstances reveal a hidden creature: it makes noise, steps into
	// the open, is searched for). Only the master. Every state of the hider goes, so every
	// creature sees it again and its attacks lose the unseen-attacker advantage. The log
	// line is the master's and the hider's player's alone ("Brisa não está mais
	// escondida"); no other player is told, and nobody is told who noticed (RN-10). The
	// master can undo it (UndoLastAction): the hiding comes back as it was.
	//
	// Errors:
	//   - `not_found`: the combat or the combatant is not in the open session.
	//   - `failed_precondition`: ContestBlocked NOT_HIDDEN, or the combat is ended.
	RevealHider(context.Context, *connect.Request[v1.RevealHiderRequest]) (*connect.Response[v1.RevealHiderResponse], error)
	// Help is the Help action in its two forms (SRD 5.1, "Help"): advantage on an ally's
	// next check of a task, or on the ally's first attack on a creature within 5 feet of
	// the helper. It spends the action. The player helps with their own combatant on its
	// turn; the master with any.
	//
	// Errors: `failed_precondition`: EncounterBlocked (NOT_ACTIVE, NOT_YOUR_TURN,
	// ACTION_USED, TARGET_OUT_OF_REACH with `missing_ft`) or ContestBlocked (NOT_AVAILABLE,
	// NOT_AN_ALLY, TASK_NOT_AVAILABLE, SURPRISED).
	Help(context.Context, *connect.Request[v1.HelpRequest]) (*connect.Response[v1.HelpResponse], error)
	// ClearHelp takes a Help back: the master, when the help should not hold any more.
	ClearHelp(context.Context, *connect.Request[v1.ClearHelpRequest]) (*connect.Response[v1.ClearHelpResponse], error)
	// SetSurprised marks a creature surprised or not, before the combat begins (SRD
	// 5.1, "Surprise"): the master, any creature, player characters included. A
	// surprised creature does not move, act, take a bonus action or react until its
	// first turn ends (the bonus action is the app's reading). The player reads only
	// their own state.
	//
	// Errors: `failed_precondition` (ContestBlocked): COMBAT_BEGUN.
	SetSurprised(context.Context, *connect.Request[v1.SetSurprisedRequest]) (*connect.Response[v1.SetSurprisedResponse], error)
	// GetSurpriseSuggestion is the app's suggestion of who is surprised: each hider's
	// Stealth against each creature's passive Perception (SRD 5.1, "Surprise"). Only the
	// master. IDEMPOTENT.
	GetSurpriseSuggestion(context.Context, *connect.Request[v1.GetSurpriseSuggestionRequest]) (*connect.Response[v1.GetSurpriseSuggestionResponse], error)
	// GetGroupCheck is the open group check of the open session, or the latest closed
	// one, as the caller reads it; none when there is not any. IDEMPOTENT.
	GetGroupCheck(context.Context, *connect.Request[v1.GetGroupCheckRequest]) (*connect.Response[v1.GetGroupCheckResponse], error)
	// RequestGroupCheck asks living player characters for a check or a saving throw, at
	// any moment out of combat (SRD 5.1, "Ability Checks", "Saving Throws"). With no
	// `character_ids` it asks every living player character, and with `group` (the
	// default for that case) the group passes when at least half of them pass (SRD 5.1,
	// "Working Together", Group Checks). With `character_ids` it asks only those
	// characters, and each roll stands alone. Only the master; one request is open at a
	// time; only the characters asked read it or may roll it (RN-10, RN-20).
	//
	// Errors:
	//   - `invalid_argument`: skill_key is not a skill, an ability check or a saving throw;
	//     a character_id is not a living player character of the campaign (an NPC, a dead
	//     or an unknown one); a repeated character_id; `group` true with only one
	//     character asked.
	//   - `failed_precondition` (ContestBlocked): GROUP_CHECK_OPEN.
	RequestGroupCheck(context.Context, *connect.Request[v1.RequestGroupCheckRequest]) (*connect.Response[v1.RequestGroupCheckResponse], error)
	// RollGroupCheck is a player's roll for the open group check, for their own
	// character, in the app or with the physical d20. Once.
	//
	// Errors: `failed_precondition`: ContestBlocked (GROUP_CHECK_CLOSED, NOT_IN_GROUP_CHECK,
	// ALREADY_ANSWERED) or EncounterBlocked WRONG_DICE_MODE.
	//
	// A character that holds a Bardic Inspiration die (given outside a combat) gets
	// `inspiration_offer` in place of the group check: the d20 is rolled and kept, the
	// check is not written, and ResourceService.AnswerOutsideInspiration settles it.
	RollGroupCheck(context.Context, *connect.Request[v1.RollGroupCheckRequest]) (*connect.Response[v1.RollGroupCheckResponse], error)
	// RollForPlayer is the master's roll for a character that has not answered.
	RollForPlayer(context.Context, *connect.Request[v1.RollForPlayerRequest]) (*connect.Response[v1.RollForPlayerResponse], error)
	// CloseGroupCheck ends the group check: the characters that did not answer count as
	// failed, and the verdict is worked out. Only the master.
	CloseGroupCheck(context.Context, *connect.Request[v1.CloseGroupCheckRequest]) (*connect.Response[v1.CloseGroupCheckResponse], error)
}

